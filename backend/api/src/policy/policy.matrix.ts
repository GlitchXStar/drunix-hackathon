import { UserRole } from '@prisma/client';

export enum Permission {
  INSTITUTION_MANAGE = 'INSTITUTION_MANAGE',
  INSTITUTION_ADMIN_CREATE = 'INSTITUTION_ADMIN_CREATE',
  USER_MANAGE_OWN_INST = 'USER_MANAGE_OWN_INST',
  PLATFORM_AUDIT_VIEW = 'PLATFORM_AUDIT_VIEW',
  INSTITUTION_AUDIT_VIEW = 'INSTITUTION_AUDIT_VIEW',
  SHARE_CODE_REDEEM = 'SHARE_CODE_REDEEM',
  REQUEST_DOCUMENTS_CREATE = 'REQUEST_DOCUMENTS_CREATE',
  REQUEST_FEATURES_CREATE = 'REQUEST_FEATURES_CREATE',
  DOCUMENT_VIEW_SESSION = 'DOCUMENT_VIEW_SESSION',
  ATTESTATION_MANAGE = 'ATTESTATION_MANAGE',
  ATTESTATION_LOOKUP = 'ATTESTATION_LOOKUP',
  ASSESSMENT_RUN_FINALISE = 'ASSESSMENT_RUN_FINALISE',
  ASSESSMENT_VIEW = 'ASSESSMENT_VIEW',
  BUSINESS_MANAGE_PROFILE = 'BUSINESS_MANAGE_PROFILE',
  DOCUMENT_UPLOAD = 'DOCUMENT_UPLOAD',
  DOCUMENT_MUTATE_DELETE = 'DOCUMENT_MUTATE_DELETE',
  BUSINESS_ACCESS_HISTORY_VIEW = 'BUSINESS_ACCESS_HISTORY_VIEW',
}

/**
 * Single policy module defining the authoritative permission matrix from SPEC.md §9.2
 */
export const PERMISSION_MATRIX: Record<Permission, UserRole[]> = {
  [Permission.INSTITUTION_MANAGE]: [UserRole.PLATFORM_SUPER_ADMIN],
  [Permission.INSTITUTION_ADMIN_CREATE]: [UserRole.PLATFORM_SUPER_ADMIN],
  [Permission.USER_MANAGE_OWN_INST]: [UserRole.INSTITUTION_ADMIN],
  [Permission.PLATFORM_AUDIT_VIEW]: [UserRole.PLATFORM_SUPER_ADMIN],
  [Permission.INSTITUTION_AUDIT_VIEW]: [UserRole.INSTITUTION_ADMIN, UserRole.COMPLIANCE_OFFICER],
  [Permission.SHARE_CODE_REDEEM]: [UserRole.KYC_OFFICER, UserRole.LOAN_OFFICER],
  [Permission.REQUEST_DOCUMENTS_CREATE]: [UserRole.KYC_OFFICER],
  [Permission.REQUEST_FEATURES_CREATE]: [UserRole.LOAN_OFFICER],
  [Permission.DOCUMENT_VIEW_SESSION]: [UserRole.KYC_OFFICER],
  [Permission.ATTESTATION_MANAGE]: [UserRole.KYC_OFFICER],
  [Permission.ATTESTATION_LOOKUP]: [UserRole.KYC_OFFICER, UserRole.COMPLIANCE_OFFICER, UserRole.LOAN_OFFICER],
  [Permission.ASSESSMENT_RUN_FINALISE]: [UserRole.LOAN_OFFICER],
  [Permission.ASSESSMENT_VIEW]: [UserRole.COMPLIANCE_OFFICER, UserRole.LOAN_OFFICER],
  [Permission.BUSINESS_MANAGE_PROFILE]: [UserRole.BUSINESS_OWNER],
  [Permission.DOCUMENT_UPLOAD]: [UserRole.BUSINESS_OWNER, UserRole.BUSINESS_EMPLOYEE],
  [Permission.DOCUMENT_MUTATE_DELETE]: [UserRole.BUSINESS_OWNER, UserRole.BUSINESS_EMPLOYEE],
  [Permission.BUSINESS_ACCESS_HISTORY_VIEW]: [UserRole.BUSINESS_OWNER],
};

/**
 * Check if a role possesses a specific permission
 */
export function hasPermission(role: UserRole, permission: Permission): boolean {
  const allowedRoles = PERMISSION_MATRIX[permission];
  if (!allowedRoles) {
    return false; // Default deny
  }
  return allowedRoles.includes(role);
}
